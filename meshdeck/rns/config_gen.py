"""Renders the managed Reticulum config from MeshDeck settings.

Pure function; heavily unit-tested. MeshDeck writes this config into its own
data dir (<data>/reticulum/config) and never touches ~/.reticulum.

Interface key facts (this rns version):
- TCPServer/TCPServerInterface & TCPClient require their canonical keys;
  normalize nothing for them (listen_ip + port / target_host + target_port).
- Backbone types: Reticulum remaps port->listen_port/target_port,
  listen_on->listen_ip, remote->target_host itself, so emitting
  listen_ip + port / target_host + target_port is safe for both.
- Public listeners (0.0.0.0): the manual mandates announce rate targets.
"""

from __future__ import annotations

from typing import Any

_HEADER = """# This file is generated by MeshDeck.
# Edit connection settings inside the app instead of here.
# (Advanced mode offers a raw editor via the "extra_config_text" escape hatch.)

"""

# Announce-rate preset for interfaces that are publicly reachable (manual
# recommendation for hosted/entrypoint-style listeners).
_PUBLIC_RATE_PRESET = """\
    announce_rate_target = 3600
    announce_rate_penalty = 3600
    announce_rate_grace = 6"""

INTERFACE_KINDS = (
    "auto",
    "tcp_server",
    "tcp_client",
    "backbone_server",
    "backbone_client",
)


def _clean(value: Any) -> str:
    """Strip characters that would break the INI syntax out of a value."""
    return str(value).replace("\n", " ").replace("\r", " ").strip()


def _is_public_ip(listen_ip: str) -> bool:
    return listen_ip in ("0.0.0.0", "::", "[::]")


def _render_tcp_client(entry: dict[str, Any], index: int) -> str:
    name = _clean(entry.get("name") or f"Entrypoint {index + 1}")
    host = _clean(entry.get("host", ""))
    port = int(entry.get("port", 4242))
    lines = [
        f"  [[{name}]]",
        "    type = TCPClientInterface",
        "    enabled = yes",
        f"    target_host = {host}",
        f"    target_port = {port}",
    ]
    return "\n".join(lines)


def render_interface(entry: dict[str, Any], index: int) -> str | None:
    """Render one entry of the structured `interfaces` settings list.

    Returns None for entries that should be skipped (disabled or unusable)."""
    if entry.get("enabled", True) is False:
        return None
    kind = entry.get("kind", "")
    name = _clean(entry.get("name") or f"Interface {index + 1}")

    if kind == "auto":
        return "\n".join(
            [f"  [[{name}]]", "    type = AutoInterface", "    enabled = yes"]
        )

    if kind in ("tcp_server", "backbone_server"):
        itype = "TCPServerInterface" if kind == "tcp_server" else "BackboneInterface"
        listen_ip = _clean(entry.get("listen_ip") or "127.0.0.1")
        port = int(entry.get("port") or 4242)
        lines = [
            f"  [[{name}]]",
            f"    type = {itype}",
            "    enabled = yes",
            f"    listen_ip = {listen_ip}",
            f"    port = {port}",
        ]
        if kind == "backbone_server" and entry.get("gateway_mode", True):
            lines.append("    mode = gateway")
        if _is_public_ip(listen_ip):
            lines.append(_PUBLIC_RATE_PRESET)
        return "\n".join(lines)

    if kind in ("tcp_client", "backbone_client"):
        itype = "TCPClientInterface" if kind == "tcp_client" else "BackboneClientInterface"
        target_host = _clean(entry.get("target_host", ""))
        if not target_host:
            return None
        target_port = int(entry.get("target_port") or 4242)
        return "\n".join(
            [
                f"  [[{name}]]",
                f"    type = {itype}",
                "    enabled = yes",
                f"    target_host = {target_host}",
                f"    target_port = {target_port}",
            ]
        )
    return None


def _split_extra_sections(extra: str) -> dict[str, list[str]]:
    """Split raw extra config text into {top_section_name: body_lines}.

    Top-level headers look like ``[name]``; sub-section headers ``[[name]]``
    stay attached to their parent's body. Headerless leading lines default to
    the "interfaces" section, since interface snippets are by far the most
    common use of this escape hatch."""
    sections: dict[str, list[str]] = {}
    current = "interfaces"
    for raw_line in extra.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("[") and not stripped.startswith("[["):
            name = stripped.strip("[]").strip()
            if name:
                current = name
                sections.setdefault(current, [])
            continue
        sections.setdefault(current, []).append(raw_line)
    return sections


def render_config(settings: dict[str, Any], log_file: str | None = None) -> str:
    """Build the Reticulum config text for the given settings dict.

    If settings["interfaces"] is non-empty it takes over interface rendering
    entirely (the structured wizard path); otherwise legacy keys are used
    (`connect_autointerface`, `public_entrypoints`, `extra_config_text`).

    The `extra_config_text` escape hatch is merged section-by-section into the
    generated sections — naively concatenating produces duplicate section
    headers, which configobj rejects with "Duplicate section name"."""
    transport = bool(settings.get("transport_enabled", False))
    log_level = int(settings.get("log_level", 4))

    interfaces_body: list[str] = []
    structured = settings.get("interfaces") or []
    if structured:
        rendered = [
            block
            for i, entry in enumerate(structured)
            if (block := render_interface(entry, i)) is not None
        ]
        if rendered:
            interfaces_body.extend("\n\n".join(rendered).splitlines())
        else:
            interfaces_body.append("  # (none — MeshDeck is offline)")
    else:
        if settings.get("connect_autointerface", True):
            interfaces_body.extend(
                [
                    "  [[Local Network]]",
                    "    type = AutoInterface",
                    "    enabled = yes",
                ]
            )
        for index, entry in enumerate(settings.get("public_entrypoints") or []):
            if not entry.get("host"):
                continue
            if interfaces_body:
                interfaces_body.append("")
            interfaces_body.extend(_render_tcp_client(entry, index).splitlines())

    sections: dict[str, Any] = {
        "reticulum": [
            f"  enable_transport = {'Yes' if transport else 'No'}",
            "  share_instance = No",
        ],
        "logging": [f"  loglevel = {log_level}"]
        + ([f"  logfile = {_clean(log_file)}"] if log_file else []),
        "interfaces": interfaces_body,
    }
    order = ["reticulum", "logging", "interfaces"]

    extra = settings.get("extra_config_text") or ""
    if isinstance(extra, str) and extra.strip():
        for name, body in _split_extra_sections(extra.strip()).items():
            if name in sections:
                sections[name].append("")
                sections[name].extend(
                    line for line in body if line.strip()
                )
            else:
                sections[name] = body
                order.append(name)

    out = [_HEADER.rstrip("\n"), ""]
    for name in order:
        out.append(f"[{name}]")
        # bare section headers on their own are valid INI; a non-indented
        # remark would confuse strict parsers, so keep bodies comment-safe
        out.extend(sections[name])
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def validate_interfaces(interfaces: list[dict[str, Any]]) -> list[str]:
    """Light sanity validation for the structured list, before render."""
    problems: list[str] = []
    for i, entry in enumerate(interfaces):
        kind = entry.get("kind")
        label = f"interface #{i + 1} ({entry.get('name') or '?'})"
        if kind not in INTERFACE_KINDS:
            problems.append(f"{label}: unknown kind {kind!r}")
            continue
        if kind in ("tcp_server", "backbone_server"):
            port = entry.get("port")
            if port is None or not (0 < int(port) < 65536):
                problems.append(f"{label}: port must be 1-65535")
        if kind in ("tcp_client", "backbone_client"):
            if not str(entry.get("target_host") or "").strip():
                problems.append(f"{label}: target_host is required")
            port = entry.get("target_port")
            if port is None or not (0 < int(port) < 65536):
                problems.append(f"{label}: target_port must be 1-65535")
    return problems
