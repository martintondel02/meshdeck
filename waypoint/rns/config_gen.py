"""Renders the managed Reticulum config from Waypoint settings.

Pure function; heavily unit-tested. Waypoint writes this config into its own
data dir (<data>/reticulum/config) and never touches ~/.reticulum.
"""

from __future__ import annotations

from typing import Any

_HEADER = """# This file is generated by Waypoint.
# Edit connection settings inside the app instead of here.
# (Advanced mode offers a raw editor via the "extra_config_text" escape hatch.)

"""


def _clean(value: Any) -> str:
    """Strip characters that would break the INI syntax out of a value."""
    return str(value).replace("\n", " ").replace("\r", " ").strip()


def _render_tcp_client(entry: dict[str, Any], index: int) -> str:
    name = _clean(entry.get("name") or f"Entrypoint {index + 1}")
    host = _clean(entry.get("host", ""))
    port = int(entry.get("port", 4242))
    lines = [
        f"  [[{name}]]",
        "    type = TCPClientInterface",
        "    enabled = yes",
        f"    target_host = {host}",
        f"    target_port = {port}",
    ]
    return "\n".join(lines)


def render_config(settings: dict[str, Any], log_file: str | None = None) -> str:
    """Build the Reticulum config text for the given settings dict."""
    transport = bool(settings.get("transport_enabled", False))
    log_level = int(settings.get("log_level", 4))

    out = [_HEADER]
    out.append("[reticulum]")
    out.append(f"  enable_transport = {'Yes' if transport else 'No'}")
    out.append("  share_instance = No")
    out.append("")

    out.append("[logging]")
    out.append(f"  loglevel = {log_level}")
    if log_file:
        out.append(f"  logfile = {_clean(log_file)}")
    out.append("")

    out.append("[interfaces]")
    rendered_any = False
    if settings.get("connect_autointerface", True):
        out.append("  [[Local Network]]")
        out.append("    type = AutoInterface")
        out.append("    enabled = yes")
        rendered_any = True

    for index, entry in enumerate(settings.get("public_entrypoints") or []):
        if not entry.get("host"):
            continue
        if rendered_any:
            out.append("")
        out.append(_render_tcp_client(entry, index))
        rendered_any = True

    extra = settings.get("extra_config_text") or ""
    if isinstance(extra, str) and extra.strip():
        out.append("")
        out.append("")
        out.append("# --- Advanced raw configuration (from Waypoint settings) ---")
        out.append(extra.strip())

    return "\n".join(out).rstrip("\n") + "\n"
